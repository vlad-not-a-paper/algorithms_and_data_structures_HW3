def feedAnimals(animals, food):
    if len(animals) == 0 or len(food) == 0:
        return 0
    animals.sort()
    food.sort()
    count = 0
    for f in food:
        if f >= animals[count]:
            count += 1
        if count == len(animals):
            break
    return count

'''
Если f >= animals[count], отдаём порцию этому животному. Таким образом, самого нетребовательного животного кормим самой маленькой подходящей порцией,
а более крупные порции остаются для более требовательных животных. Если в оптимальном случае порции распределены иначе,
их можно поменять местами, и число накормленных не уменьшится, поэтому жадный алгоритм не хуже оптимального.
'''