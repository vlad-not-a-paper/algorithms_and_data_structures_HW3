def extraLetter(a, b):
    hashMapA = {}
    for ch in a:
        hashMapA[ch] = hashMapA.get(ch, 0) + 1
    for ch in b:
        if hashMapA.get(ch, 0) == 0:
            return ch
        hashMapA[ch] -= 1
    return ""

'''
Считаем, сколько раз каждая буква встречается в a. Потом идём по b и вычитаем буквы из счётчика. Первая буква, для которой счётчик уже 0
(или которой не было в a), и есть лишняя. Каждая строка проходится один раз, обращение к словарю — O(1), поэтому сложность O(n).
'''